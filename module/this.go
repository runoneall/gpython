func rot13(s string) string {
	out := make([]byte, len(s))
	for i := 0; i < len(s); i++ {
		c := s[i]
		switch {
		case c >= 'a' && c <= 'z':
			out[i] = 'a' + (c-'a'+13)%26
		case c >= 'A' && c <= 'Z':
			out[i] = 'A' + (c-'A'+13)%26
		default:
			out[i] = c
		}
	}
	return string(out)
}

func newThisModule() *object.Module {
	m := object.NewModule("this")
	m.Dict["s"] = object.NewStr(thisSource)
	m.Dict["d"] = object.NewDict()
	m.Dict["c"] = object.NewInt(97)
	print(rot13(thisSource))
	return m
}
